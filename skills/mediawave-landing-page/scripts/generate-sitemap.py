#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
MediaWave Sitemap Generator
============================
Generates sitemap.xml and robots.txt for Hebrew landing pages.
Creates entries for the main page and standard legal pages.

Usage:
    python generate-sitemap.py https://example.co.il
    python generate-sitemap.py https://example.co.il -o output/
    python generate-sitemap.py https://example.co.il --pages /about /contact
"""

import argparse
import os
import sys
from datetime import datetime
from xml.etree.ElementTree import Element, SubElement, ElementTree, tostring
from xml.dom.minidom import parseString


# ---------------------------------------------------------------------------
# Sitemap Generator
# ---------------------------------------------------------------------------

def generate_sitemap_xml(base_url, extra_pages=None, lastmod=None):
    """
    Generate a sitemap.xml string.

    Args:
        base_url: The base URL (e.g., https://example.co.il)
        extra_pages: List of dicts with keys: path, priority, changefreq
        lastmod: Last modification date string (YYYY-MM-DD). Defaults to today.

    Returns:
        XML string of the sitemap.
    """
    if lastmod is None:
        lastmod = datetime.now().strftime("%Y-%m-%d")

    # Ensure base URL has no trailing slash
    base_url = base_url.rstrip("/")

    # Default pages for a landing page project
    pages = [
        {"path": "/", "priority": "1.0", "changefreq": "weekly"},
        {"path": "/privacy", "priority": "0.3", "changefreq": "monthly"},
        {"path": "/terms", "priority": "0.3", "changefreq": "monthly"},
        {"path": "/accessibility", "priority": "0.3", "changefreq": "monthly"},
    ]

    # Add extra pages
    if extra_pages:
        for page in extra_pages:
            if isinstance(page, str):
                page = {"path": page, "priority": "0.5", "changefreq": "monthly"}
            # Avoid duplicates
            existing_paths = [p["path"] for p in pages]
            if page["path"] not in existing_paths:
                pages.append(page)

    # Build XML
    urlset = Element("urlset")
    urlset.set("xmlns", "http://www.sitemaps.org/schemas/sitemap/0.9")
    urlset.set("xmlns:xhtml", "http://www.w3.org/1999/xhtml")

    for page in pages:
        url_elem = SubElement(urlset, "url")

        loc = SubElement(url_elem, "loc")
        path = page["path"]
        if path == "/":
            loc.text = base_url + "/"
        else:
            loc.text = base_url + path

        lastmod_elem = SubElement(url_elem, "lastmod")
        lastmod_elem.text = lastmod

        changefreq_elem = SubElement(url_elem, "changefreq")
        changefreq_elem.text = page.get("changefreq", "monthly")

        priority_elem = SubElement(url_elem, "priority")
        priority_elem.text = page.get("priority", "0.5")

        # Add hreflang for Hebrew
        xhtml_link = SubElement(url_elem, "xhtml:link")
        xhtml_link.set("rel", "alternate")
        xhtml_link.set("hreflang", "he")
        if path == "/":
            xhtml_link.set("href", base_url + "/")
        else:
            xhtml_link.set("href", base_url + path)

    # Convert to pretty XML string
    rough_string = tostring(urlset, encoding="unicode")
    dom = parseString(rough_string)
    pretty_xml = dom.toprettyxml(indent="  ", encoding=None)

    # Remove the extra XML declaration that minidom adds (we add our own)
    lines = pretty_xml.split("\n")
    if lines and lines[0].startswith("<?xml"):
        lines = lines[1:]
    xml_body = "\n".join(lines).strip()

    return '<?xml version="1.0" encoding="UTF-8"?>\n' + xml_body + "\n"


# ---------------------------------------------------------------------------
# Robots.txt Generator
# ---------------------------------------------------------------------------

def generate_robots_txt(base_url, sitemap_path="/sitemap.xml", extra_rules=None):
    """
    Generate a minimal robots.txt that references the sitemap.

    Args:
        base_url: The base URL
        sitemap_path: Path to sitemap relative to base URL
        extra_rules: List of additional rules (strings)

    Returns:
        robots.txt content string.
    """
    base_url = base_url.rstrip("/")

    lines = [
        "# robots.txt - Generated by MediaWave SEO Tools",
        f"# Site: {base_url}",
        f"# Generated: {datetime.now().strftime('%Y-%m-%d')}",
        "",
        "User-agent: *",
        "Allow: /",
        "",
        "# Disallow admin/API paths",
        "Disallow: /api/",
        "Disallow: /admin/",
        "Disallow: /_next/",
        "",
    ]

    if extra_rules:
        for rule in extra_rules:
            lines.append(rule)
        lines.append("")

    lines.append(f"Sitemap: {base_url}{sitemap_path}")
    lines.append("")

    return "\n".join(lines)


# ---------------------------------------------------------------------------
# Main
# ---------------------------------------------------------------------------

def main():
    parser = argparse.ArgumentParser(
        description="MediaWave Sitemap Generator - Create sitemap.xml and robots.txt for landing pages",
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog="""
Examples:
  python generate-sitemap.py https://example.co.il
  python generate-sitemap.py https://example.co.il -o build/
  python generate-sitemap.py https://example.co.il --pages /about /contact /gallery
  python generate-sitemap.py https://example.co.il --no-robots
        """
    )
    parser.add_argument("base_url",
                        help="Base URL of the website (e.g., https://example.co.il)")
    parser.add_argument("-o", "--output-dir",
                        help="Output directory for files (default: current directory)")
    parser.add_argument("--pages", nargs="*",
                        help="Additional pages to include (paths like /about /contact)")
    parser.add_argument("--lastmod",
                        help="Last modification date (YYYY-MM-DD, default: today)")
    parser.add_argument("--no-robots", action="store_true",
                        help="Skip generating robots.txt")
    parser.add_argument("--stdout", action="store_true",
                        help="Print to stdout instead of writing files")

    args = parser.parse_args()

    # Validate URL
    base_url = args.base_url
    if not base_url.startswith("http://") and not base_url.startswith("https://"):
        print("Warning: URL does not start with http(s)://, adding https://", file=sys.stderr)
        base_url = "https://" + base_url

    # Parse extra pages
    extra_pages = None
    if args.pages:
        extra_pages = []
        for page_path in args.pages:
            if not page_path.startswith("/"):
                page_path = "/" + page_path
            extra_pages.append({
                "path": page_path,
                "priority": "0.5",
                "changefreq": "monthly"
            })

    # Generate sitemap
    sitemap_xml = generate_sitemap_xml(base_url, extra_pages, args.lastmod)

    # Generate robots.txt
    robots_txt = None
    if not args.no_robots:
        robots_txt = generate_robots_txt(base_url)

    # Output
    if args.stdout:
        print("<!-- sitemap.xml -->")
        print(sitemap_xml)
        if robots_txt:
            print("\n# --- robots.txt ---")
            print(robots_txt)
    else:
        output_dir = os.path.abspath(args.output_dir) if args.output_dir else os.getcwd()
        os.makedirs(output_dir, exist_ok=True)

        # Write sitemap.xml
        sitemap_path = os.path.join(output_dir, "sitemap.xml")
        with open(sitemap_path, "w", encoding="utf-8") as f:
            f.write(sitemap_xml)
        print(f"Created: {sitemap_path}")

        # Write robots.txt
        if robots_txt:
            robots_path = os.path.join(output_dir, "robots.txt")
            with open(robots_path, "w", encoding="utf-8") as f:
                f.write(robots_txt)
            print(f"Created: {robots_path}")

    # Summary
    page_count = 4 + (len(extra_pages) if extra_pages else 0)
    print(f"\nSitemap contains {page_count} URLs", file=sys.stderr)
    print(f"Base URL: {base_url}", file=sys.stderr)


if __name__ == "__main__":
    main()
