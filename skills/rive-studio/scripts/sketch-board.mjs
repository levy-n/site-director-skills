// sketch-board.mjs - build one self-contained board.html from the motion sketches in a folder (a.html, b.html, c.html).
// Each sketch is inlined into its own iframe through srcdoc, so the board works from any location: the browser pane,
// a file sent to the user, or a published page. Usage:
//   node sketch-board.mjs design/rive/<piece>/sketches [--title "<piece name>"] [--serve [port]]
// Writes <folder>/board.html and prints its absolute path and file URL. With --serve it also serves the folder on
// 127.0.0.1 (default port 5198) until stopped: run it in the background when the browser pane shows file URLs
// outside the session's project folders only as static snapshots.
import fs from 'node:fs';
import path from 'node:path';
import http from 'node:http';
import { pathToFileURL } from 'node:url';

const argv = process.argv.slice(2);
if (!argv.length || argv.includes('--help') || argv.includes('-h')) {
  console.log('usage: node sketch-board.mjs <sketches-folder> [--title "<piece name>"]   writes <folder>/board.html');
  process.exit(argv.length ? 0 : 2);
}
const dir = path.resolve(argv[0]);
const ti = argv.indexOf('--title');
const title = ti >= 0 && argv[ti + 1] ? argv[ti + 1] : path.basename(path.dirname(dir));
if (!fs.existsSync(dir)) { console.error(`sketch-board: folder not found: ${dir}`); process.exit(2); }

const sketches = fs.readdirSync(dir)
  .filter((f) => /^[a-z]\.html$/i.test(f))
  .sort();
if (sketches.length < 2) { console.error(`sketch-board: need at least two sketches named a.html, b.html... in ${dir}`); process.exit(2); }

const attr = (s) => s.replace(/&/g, '&amp;').replace(/"/g, '&quot;');
const esc = (s) => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
const figures = sketches.map((f) => {
  const html = fs.readFileSync(path.join(dir, f), 'utf8');
  const name = (html.match(/title:\s*'([^']*)'/) || [])[1] || f.replace('.html', '').toUpperCase();
  return `  <figure><figcaption>${esc(name)}</figcaption><iframe title="${attr(name)}" srcdoc="${attr(html)}"></iframe></figure>`;
}).join('\n');

const board = `<!doctype html>
<!-- generated by rive-studio/scripts/sketch-board.mjs from ${sketches.join(', ')}; regenerate after editing a sketch -->
<html lang="he" dir="rtl">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>${esc(title)}: סקיצות תנועה</title>
<style>
  :root { --bg: #eceef2; --fg: #15171c; --muted: #5b6370; }
  body { margin: 0; background: var(--bg); color: var(--fg); font: 15px/1.45 system-ui, sans-serif; }
  header { padding: 16px; }
  h1 { margin: 0 0 4px; font-size: 19px; }
  p { margin: 0; color: var(--muted); }
  .board { display: grid; gap: 14px; padding: 0 16px 24px; grid-template-columns: repeat(auto-fit, minmax(320px, 1fr)); }
  figure { margin: 0; }
  figcaption { font-weight: 700; margin: 0 0 6px; }
  iframe { width: 100%; height: 640px; border: 0; border-radius: 14px; background: #fff; }
</style>
</head>
<body>
<header>
  <h1>${esc(title)}: ${sketches.length} סקיצות תנועה</h1>
  <p>רחף, לחץ ונווט במקלדת. אפשר להאט ל-0.25x, להפעיל תנועה מופחתת ולהחליף כיוון. בוחרים אחרי שראית את כולן.</p>
</header>
<main class="board">
${figures}
</main>
</body>
</html>
`;
const out = path.join(dir, 'board.html');
fs.writeFileSync(out, board);
console.log(`sketch-board: wrote ${out}\n${pathToFileURL(out).href}`);

const si = argv.indexOf('--serve');
if (si >= 0) {
  const port = Number(argv[si + 1]) || 5198;
  http.createServer((req, res) => {
    const file = path.join(dir, path.basename(decodeURIComponent(req.url.split('?')[0])) || 'board.html');
    if (!fs.existsSync(file) || !fs.statSync(file).isFile()) { res.writeHead(404); return res.end(); }
    res.writeHead(200, { 'content-type': file.endsWith('.html') ? 'text/html; charset=utf-8' : 'application/octet-stream' });
    res.end(fs.readFileSync(file));
  }).listen(port, '127.0.0.1', () => console.log(`sketch-board: serving http://127.0.0.1:${port}/board.html (Ctrl+C to stop)`))
    .on('error', (e) => { console.error(`sketch-board: cannot serve on ${port}: ${e.message}`); process.exit(2); });
}
