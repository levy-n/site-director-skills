// rive-probe.mjs - load a .riv in headless Chrome with the official Rive web runtime and report what it really contains.
// Usage:
//   node rive-probe.mjs <file.riv> [--out probe.json] [--artboard Name] [--state-machine Name]
//   node rive-probe.mjs <file.riv> --contract design/rive/<piece>/CONTRACT.md [--shots <dir>] [--size 800x600]
//   node rive-probe.mjs --contract design/rive/<piece>/CONTRACT.md --emit-ts src/rive/<piece>.contract.ts
// Options:
//   --renderer canvas-lite|canvas|webgl2
//                             runtime package to load. Default: the one the project ships: canvas-lite when
//                             package.json lists @rive-app/canvas-lite or @rive-app/react-canvas-lite, else
//                             webgl2 when it is installed, else canvas
//   --runtime-version <v>     CDN version used when the chosen runtime is not installed (default: the exact
//                             @rive-app/canvas-lite version pinned in package.json, else 2.44.2)
//   --chrome <path>           Chrome or Edge for puppeteer-core (auto-detected on Windows, macOS and Linux)
//   --modules <dir>           also resolve puppeteer and the runtime from <dir>/node_modules (tooling kept outside the repo)
//   --json                    print the report as JSON only
// Needs Node 20+, and puppeteer (npm i -D puppeteer) or puppeteer-core plus a local Chrome or Edge.
// Exit codes: 0 ok, 1 contract mismatch, 2 setup error, 3 the runtime could not load the file.
import fs from 'node:fs';
import path from 'node:path';
import http from 'node:http';
import { createRequire } from 'node:module';
import { pathToFileURL } from 'node:url';

const argv = process.argv.slice(2);
if (!argv.length || argv.includes('--help') || argv.includes('-h')) {
  // print the leading comment block only
  const self = fs.readFileSync(new URL(import.meta.url), 'utf8').split(/\r?\n/);
  const end = self.findIndex((l) => !l.startsWith('//'));
  console.log(self.slice(0, end < 0 ? self.length : end).map((l) => l.replace(/^\/\/ ?/, '')).join('\n'));
  process.exit(0);
}
const opt = (name, def) => { const i = argv.indexOf(name); return i >= 0 && argv[i + 1] && !argv[i + 1].startsWith('--') ? argv[i + 1] : def; };
const flag = (name) => argv.includes(name);
const fail = (code, msg) => { console.error(`rive-probe: ${msg}`); process.exit(code); };
const VALUE_FLAGS = new Set(['--out', '--artboard', '--state-machine', '--contract', '--shots', '--size', '--emit-ts', '--renderer', '--runtime-version', '--chrome', '--modules']);
const positional = argv.filter((a, i) => !a.startsWith('--') && !VALUE_FLAGS.has(argv[i - 1]));
const rivPath = positional[0];
const contractPath = opt('--contract');
const asJson = flag('--json');

// ---------- contract ----------
function readContract(p) {
  if (!fs.existsSync(p)) fail(2, `contract not found: ${p}`);
  const text = fs.readFileSync(p, 'utf8');
  const raw = p.endsWith('.json') ? text : (text.match(/```json\r?\n([\s\S]*?)```/) || [])[1];
  if (!raw) fail(2, `no json block in ${p}`);
  try { return JSON.parse(raw); } catch (e) { return fail(2, `contract json does not parse: ${e.message}`); }
}
const contract = contractPath ? readContract(contractPath) : null;

// ---------- --emit-ts (no browser needed) ----------
function emitTs(c, out) {
  const base = (c.file || path.basename(out)).replace(/\.(riv|ts)$/i, '').replace(/[^A-Za-z0-9]+/g, '_');
  const constName = base.toUpperCase().replace(/^(\d)/, '_$1');
  const pascal = base.split('_').filter(Boolean).map((s) => s[0].toUpperCase() + s.slice(1)).join('');
  const names = (arr) => Object.fromEntries((arr || []).map((n) => [n, n]));
  const props = (c.viewModels || []).flatMap((vm) => vm.properties || []);
  const tsType = (p) => ({ boolean: 'boolean', number: 'number', color: 'number', string: 'string' }[p.type]
    || (p.type === 'enum' ? (p.enum || 'string') : 'unknown'));
  const lines = [
    `// Generated by rive-studio/scripts/rive-probe.mjs --emit-ts from ${contractPath}. Regenerate after every contract change.`,
    `export const ${constName} = ${JSON.stringify({
      file: c.file,
      artboards: names((c.artboards || []).map((a) => a.name)),
      stateMachines: names((c.artboards || []).flatMap((a) => a.stateMachines || [])),
      viewModels: names((c.viewModels || []).map((v) => v.name)),
      props: names(props.map((p) => p.name)),
      events: names(c.events),
    }, null, 2)} as const;`,
    ...(c.enums || []).map((e) => `export type ${e.name} = ${e.values.map((v) => `'${v}'`).join(' | ')};`),
    `export type ${pascal}Values = {`,
    ...props.filter((p) => p.type !== 'trigger' && (p.direction || 'app-to-rive') !== 'rive-to-app')
      .map((p) => `  ${p.name}?: ${tsType(p)};`),
    `};`,
    `export type ${pascal}Trigger = ${props.filter((p) => p.type === 'trigger').map((p) => `'${p.name}'`).join(' | ') || 'never'};`,
    '',
  ];
  fs.mkdirSync(path.dirname(path.resolve(out)), { recursive: true });
  fs.writeFileSync(out, lines.join('\n'));
  console.log(`rive-probe: wrote ${out}`);
}
if (opt('--emit-ts')) {
  if (!contract) fail(2, '--emit-ts needs --contract');
  emitTs(contract, opt('--emit-ts'));
  if (!rivPath) process.exit(0);
}
if (!rivPath) fail(2, 'pass a .riv file (see --help)');
if (!fs.existsSync(rivPath)) fail(2, `file not found: ${rivPath}`);
const rivBytes = fs.readFileSync(rivPath);

// ---------- resolve puppeteer and the runtime from the project ----------
// The project first (so the probe tests the runtime that ships), then an optional tooling folder.
const resolvers = [process.cwd(), opt('--modules')].filter(Boolean).map((d) => createRequire(path.join(path.resolve(d), 'noop.js')));
const tryResolve = (id) => { for (const r of resolvers) { try { return r.resolve(id); } catch { /* next */ } } return null; };
let puppeteer, executablePath;
const full = tryResolve('puppeteer');
const core = tryResolve('puppeteer-core');
if (full) puppeteer = (await import(pathToFileURL(full).href)).default;
else if (core) {
  puppeteer = (await import(pathToFileURL(core).href)).default;
  const candidates = [opt('--chrome'),
    'C:/Program Files/Google/Chrome/Application/chrome.exe', 'C:/Program Files (x86)/Google/Chrome/Application/chrome.exe',
    'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe', 'C:/Program Files/Microsoft/Edge/Application/msedge.exe',
    '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome', '/usr/bin/google-chrome', '/usr/bin/chromium', '/usr/bin/chromium-browser'];
  executablePath = candidates.find((c) => c && fs.existsSync(c));
  if (!executablePath) fail(2, 'puppeteer-core found but no Chrome or Edge; pass --chrome <path>');
} else fail(2, 'no puppeteer found: ask before installing, then npm i -D puppeteer-core (uses the local Chrome or Edge), or pass --modules <folder with node_modules>');

const RENDERERS = ['canvas-lite', 'canvas', 'webgl2'];
const wanted = opt('--renderer');
if (wanted && !RENDERERS.includes(wanted)) fail(2, `--renderer must be one of ${RENDERERS.join(', ')}, got "${wanted}"`);
// The project's declared dependencies decide which runtime ships. A site on canvas-lite must be probed
// with canvas-lite: the larger builds also draw text and layouts, which lite cannot, so they would pass
// a file the site then shows broken, and they report a different runtime than the one the site loads.
const declared = (() => {
  try {
    const pkg = JSON.parse(fs.readFileSync(path.resolve('package.json'), 'utf8'));
    return { ...pkg.optionalDependencies, ...pkg.devDependencies, ...pkg.dependencies };
  } catch { return {}; } // no readable package.json here: fall back to what is installed
})();
const listsLite = Boolean(declared['@rive-app/canvas-lite'] || declared['@rive-app/react-canvas-lite']);
// A runtime package, found directly or through its React wrapper, which depends on it (strict
// installers such as pnpm keep it nested there).
const pkgDir = (name) => {
  const direct = tryResolve(`@rive-app/${name}/package.json`);
  if (direct) return path.dirname(direct);
  const wrapper = tryResolve(`@rive-app/react-${name}/package.json`);
  if (!wrapper) return null;
  try { return path.dirname(createRequire(wrapper).resolve(`@rive-app/${name}/package.json`)); } catch { return null; }
};
const renderer = wanted || (listsLite ? 'canvas-lite' : pkgDir('webgl2') ? 'webgl2' : 'canvas');
const localRuntime = pkgDir(renderer);
// Without a local copy, load the version the project pins (exact versions only), so the CDN build matches.
const pinnedLite = /^\d+\.\d+\.\d+$/.test(declared['@rive-app/canvas-lite'] || '') ? declared['@rive-app/canvas-lite'] : null;
const runtimeVersion = localRuntime ? JSON.parse(fs.readFileSync(path.join(localRuntime, 'package.json'), 'utf8')).version
  : opt('--runtime-version', (renderer === 'canvas-lite' && pinnedLite) || '2.44.2');
if (!localRuntime) console.error(`rive-probe: @rive-app/${renderer} is not installed here; loading ${runtimeVersion} from the CDN`);
// Only the React wrapper declared: it pins its own canvas-lite version (react-canvas-lite 4.36.0 depends on
// canvas-lite 2.44.0), which the default above may not match. Say how to find it rather than guess.
const wrapperSpec = declared['@rive-app/react-canvas-lite'];
if (!localRuntime && renderer === 'canvas-lite' && !pinnedLite && wrapperSpec && !opt('--runtime-version')) {
  const v = String(wrapperSpec).replace(/^[\^~=v]+/, '');
  console.error(`rive-probe: @rive-app/react-canvas-lite pins its own canvas-lite version; pass it as --runtime-version (npm view @rive-app/react-canvas-lite@${v} dependencies) so the probe tests the runtime the site ships`);
}
const runtimeSrc = localRuntime ? '/rt/rive.js' : `https://unpkg.com/@rive-app/${renderer}@${runtimeVersion}/rive.js`;

// ---------- tiny server: the probe page, the file, the local runtime ----------
const [W, H] = (opt('--size', '800x600')).split('x').map(Number);
const page = `<!doctype html><meta charset="utf-8"><body style="margin:0;background:#fff">
<canvas id="c" width="${W}" height="${H}" style="width:${W}px;height:${H}px;display:block"></canvas>
<script src="${runtimeSrc}"></script>
<script>
${localRuntime ? "rive.RuntimeLoader.setWasmUrl('/rt/rive.wasm');" : ''}
const INPUT = { 56: 'number', 58: 'trigger', 59: 'boolean' };
const norm = (t) => { const s = String(t).toLowerCase(); return ({ enumtype: 'enum', assetimage: 'image', viewmodel: 'viewModel', integer: 'number', listindex: 'listIndex' })[s] || s; };
function make(opts) {
  return new Promise((resolve, reject) => {
    const r = new rive.Rive({ src: '/file.riv', canvas: document.getElementById('c'), autoplay: true, autoBind: true,
      layout: new rive.Layout({ fit: rive.Fit.Contain, alignment: rive.Alignment.Center }), ...opts,
      onLoad: () => resolve(r), onLoadError: (e) => reject(new Error(String(e && (e.data || e.message) || e).split(String.fromCharCode(10))[0])) });
  });
}
const safe = (f, d) => { try { const v = f(); return v === undefined ? d : v; } catch (e) { return d; } };
window.inspect = async (opts) => {
  const r = await make(opts);
  const contents = safe(() => r.contents, { artboards: [] });
  const artboards = (contents.artboards || []).map((a) => ({ name: a.name, animations: a.animations || [],
    stateMachines: (a.stateMachines || []).map((s) => ({ name: s.name, inputs: (s.inputs || []).map((i) => ({ name: i.name, type: INPUT[i.type] || String(i.type) })) })) }));
  const viewModels = [];
  for (let i = 0; i < safe(() => r.viewModelCount, 0); i++) {
    const vm = safe(() => r.viewModelByIndex(i), null); if (!vm) continue;
    viewModels.push({ name: vm.name, instanceCount: safe(() => vm.instanceCount, null),
      properties: safe(() => vm.properties, []).map((p) => ({ name: p.name, type: norm(p.type), rawType: String(p.type) })) });
  }
  const enums = safe(() => r.enums(), []).map((e) => ({ name: e.name, values: [...(e.values || [])] }));
  const out = { runtime: '${renderer}@${runtimeVersion}', activeArtboard: safe(() => r.activeArtboard, null),
    stateMachineNames: safe(() => r.stateMachineNames, []), defaultViewModel: safe(() => r.defaultViewModel().name, null),
    boundInstance: safe(() => r.viewModelInstance && r.viewModelInstance.viewModelName, null), artboards, viewModels, enums };
  r.cleanup();
  return out;
};
window.defaultVmFor = async (artboard) => { const r = await make({ artboard, autoplay: false }); const n = safe(() => r.defaultViewModel().name, null); r.cleanup(); return n; };
function setValue(r, vmi, name, value, sm) {
  if (vmi) {
    const tries = typeof value === 'boolean' ? ['boolean'] : typeof value === 'number' ? ['number', 'color'] : ['enum', 'string'];
    for (const t of tries) { const p = safe(() => vmi[t](name), null); if (p) { p.value = value; return 'vm'; } }
  }
  const input = safe(() => r.stateMachineInputs(sm), []).find((i) => i.name === name);
  if (input) { input.value = value; return 'input'; }
  return null;
}
window.shot = async (s, sm, artboard) => {
  const r = await make({ artboard, stateMachine: sm });
  const vmi = safe(() => r.viewModelInstance, null);
  const events = [], misses = [];
  safe(() => r.on(rive.EventType.RiveEvent, (e) => events.push(e.data && e.data.name)));
  for (const [k, v] of Object.entries(s.set || {})) if (!setValue(r, vmi, k, v, sm)) misses.push(k);
  for (const t of s.fire || []) {
    const p = safe(() => vmi && vmi.trigger(t), null);
    if (p) p.trigger(); else { const i = safe(() => r.stateMachineInputs(sm), []).find((x) => x.name === t); if (i) i.fire(); else misses.push(t); }
  }
  await new Promise((res) => setTimeout(res, s.advanceMs ?? 500));
  window.__last = r;
  return { events, misses };
};
window.dispose = () => { if (window.__last) window.__last.cleanup(); window.__last = null; };
</script>`;
const server = http.createServer((q, s) => {
  const u = decodeURIComponent(q.url.split('?')[0]);
  if (u === '/' || u === '/probe.html') { s.writeHead(200, { 'content-type': 'text/html' }); return s.end(page); }
  if (u === '/file.riv') { s.writeHead(200, { 'content-type': 'application/octet-stream' }); return s.end(rivBytes); }
  if (localRuntime && u.startsWith('/rt/')) {
    const f = path.join(localRuntime, path.basename(u));
    if (fs.existsSync(f)) { s.writeHead(200, { 'content-type': f.endsWith('.wasm') ? 'application/wasm' : 'text/javascript' }); return s.end(fs.readFileSync(f)); }
  }
  s.writeHead(404); s.end();
});
await new Promise((r) => server.listen(0, '127.0.0.1', r));
const base = `http://127.0.0.1:${server.address().port}`;

// ---------- run ----------
const browser = await puppeteer.launch({ headless: true, executablePath,
  args: ['--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--no-first-run'] });
const exit = async (code) => { await browser.close().catch(() => {}); server.close(); process.exit(code); };
try {
  const tab = await browser.newPage();
  await tab.setViewport({ width: W, height: H, deviceScaleFactor: 1 });
  await tab.emulateMediaFeatures([{ name: 'prefers-reduced-motion', value: 'no-preference' }]);
  const consoleErrors = [];
  tab.on('console', (m) => { if (m.type() === 'error') consoleErrors.push(m.text()); });
  await tab.goto(`${base}/probe.html`, { waitUntil: 'load' });
  const loadOpts = { ...(opt('--artboard') ? { artboard: opt('--artboard') } : {}), ...(opt('--state-machine') ? { stateMachine: opt('--state-machine') } : {}) };
  let report;
  try { report = await tab.evaluate((o) => window.inspect(o), loadOpts); }
  catch (e) { console.error(consoleErrors.join('\n')); fail(3, `the runtime could not load ${rivPath}: ${e.message}`); }
  report.file = path.basename(rivPath);
  report.sizeKB = Math.round(rivBytes.length / 102.4) / 10;
  for (const a of report.artboards) a.defaultViewModel = await tab.evaluate((n) => window.defaultVmFor(n), a.name).catch(() => null);

  // ---------- contract diff ----------
  const errors = [], warnings = [];
  if (contract) {
    const abs = new Map(report.artboards.map((a) => [a.name, a]));
    for (const ca of contract.artboards || []) {
      const a = abs.get(ca.name);
      if (!a) { errors.push(`artboard "${ca.name}" missing (found: ${[...abs.keys()].join(', ') || 'none'}); drafts that are not Components are not exported`); continue; }
      for (const sm of ca.stateMachines || []) if (!a.stateMachines.some((s) => s.name === sm)) errors.push(`state machine "${sm}" missing on "${ca.name}" (found: ${a.stateMachines.map((s) => s.name).join(', ') || 'none'})`);
      if (ca.viewModel && a.defaultViewModel && a.defaultViewModel !== ca.viewModel) errors.push(`artboard "${ca.name}" is bound to view model "${a.defaultViewModel}", contract says "${ca.viewModel}"`);
      if (ca.viewModel && !a.defaultViewModel) warnings.push(`artboard "${ca.name}": no default view model reported; check the binding in the editor`);
    }
    const vms = new Map(report.viewModels.map((v) => [v.name, v]));
    for (const cv of contract.viewModels || []) {
      const v = vms.get(cv.name);
      if (!v) { errors.push(`view model "${cv.name}" missing (found: ${[...vms.keys()].join(', ') || 'none'})`); continue; }
      const props = new Map(v.properties.map((p) => [p.name, p]));
      for (const cp of cv.properties || []) {
        const p = props.get(cp.name);
        if (!p) errors.push(`${cv.name}.${cp.name} missing`);
        else if (p.type !== cp.type) errors.push(`${cv.name}.${cp.name} is ${p.type} (raw ${p.rawType}), contract says ${cp.type}`);
      }
      for (const p of v.properties) if (!(cv.properties || []).some((cp) => cp.name === p.name)) warnings.push(`${cv.name}.${p.name} (${p.type}) is in the file but not in the contract`);
    }
    const ens = new Map(report.enums.map((e) => [e.name, e]));
    for (const ce of contract.enums || []) {
      const e = ens.get(ce.name);
      if (!e) { errors.push(`enum "${ce.name}" missing`); continue; }
      const a = [...e.values].sort().join('|'), b = [...ce.values].sort().join('|');
      if (a !== b) errors.push(`enum "${ce.name}" values [${e.values.join(', ')}] differ from contract [${ce.values.join(', ')}]`);
      else if (e.values.join('|') !== ce.values.join('|')) warnings.push(`enum "${ce.name}" has the same values in a different order`);
    }
    if (contract.maxKB && report.sizeKB > contract.maxKB) errors.push(`file is ${report.sizeKB} KB, budget ${contract.maxKB} KB`);
  }

  // ---------- shots ----------
  const shotsDir = opt('--shots');
  report.shots = [];
  if (shotsDir) {
    if (!contract?.shots?.length) warnings.push('--shots given but the contract has no "shots" array');
    fs.mkdirSync(shotsDir, { recursive: true });
    const ab = contract?.artboards?.[0];
    const sm = ab?.stateMachines?.[0] || report.stateMachineNames[0];
    const seenEvents = new Set();
    const abMissing = ab && !report.artboards.some((a) => a.name === ab.name);
    if (abMissing) errors.push(`shots skipped: artboard "${ab.name}" is not in the file`);
    for (const s of abMissing ? [] : contract?.shots || []) {
      const res = await tab.evaluate((x, m, a) => window.shot(x, m, a), s, sm, ab?.name).catch((e) => ({ error: e.message }));
      const file = path.join(shotsDir, `${s.name}.png`);
      if (!res.error) await (await tab.$('#c')).screenshot({ path: file });
      await tab.evaluate(() => window.dispose());
      (res.events || []).forEach((e) => seenEvents.add(e));
      if (res.misses?.length) errors.push(`shot "${s.name}": no property or input named ${res.misses.join(', ')}`);
      if (res.error) errors.push(`shot "${s.name}" failed: ${res.error}`);
      report.shots.push({ name: s.name, file, ...res });
    }
    for (const ev of contract?.events || []) if (!seenEvents.has(ev)) warnings.push(`event "${ev}" did not fire during the shots (not verified)`);
    if (report.shots.length) {
      const cells = report.shots.filter((s) => !s.error).map((s) => `<figure style="margin:0"><img src="data:image/png;base64,${fs.readFileSync(s.file).toString('base64')}" style="width:100%;border:1px solid #ddd;border-radius:8px"><figcaption style="font:13px system-ui;padding:4px 0">${s.name}</figcaption></figure>`).join('');
      await tab.setViewport({ width: 1200, height: 100 }); // fullPage grows to the content height
      await tab.setContent(`<body style="margin:16px;background:#fff"><div style="display:grid;grid-template-columns:repeat(3,1fr);gap:12px">${cells}</div></body>`);
      await tab.screenshot({ path: path.join(shotsDir, 'contact-sheet.png'), fullPage: true });
    }
  }
  report.errors = errors; report.warnings = warnings; report.consoleErrors = consoleErrors;
  if (opt('--out')) fs.writeFileSync(opt('--out'), JSON.stringify(report, null, 2));

  // ---------- print ----------
  if (asJson) console.log(JSON.stringify(report, null, 2));
  else {
    console.log(`${report.file}  ${report.sizeKB} KB  runtime ${report.runtime} (${localRuntime ? 'project' : 'CDN'})`);
    for (const a of report.artboards) {
      console.log(`artboard ${a.name}${a.name === report.activeArtboard ? ' (default)' : ''}  view model: ${a.defaultViewModel ?? '-'}`);
      for (const s of a.stateMachines) console.log(`  state machine ${s.name}${s.inputs.length ? `  inputs (legacy): ${s.inputs.map((i) => `${i.name}:${i.type}`).join(', ')}` : ''}`);
      if (a.animations.length) console.log(`  timelines: ${a.animations.join(', ')}`);
    }
    for (const v of report.viewModels) console.log(`view model ${v.name}: ${v.properties.map((p) => `${p.name}:${p.type}`).join(', ') || '(no properties)'}`);
    for (const e of report.enums) console.log(`enum ${e.name}: ${e.values.join(', ')}`);
    for (const s of report.shots) console.log(`shot ${s.name}: ${s.error ? `FAILED ${s.error}` : s.file}`);
    warnings.forEach((w) => console.log(`warn  ${w}`));
    errors.forEach((e) => console.log(`ERROR ${e}`));
    if (contract) console.log(errors.length ? `\ncontract: ${errors.length} differences` : '\ncontract: the file matches');
  }
  await exit(errors.length ? 1 : 0);
} catch (e) {
  console.error(`rive-probe: ${e.stack || e.message}`);
  await exit(2);
}
